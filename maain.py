import turtle

turtle.Screen().bgcolor("blue")
sc= turtle.Screen()
sc.setup(400,300)
sc.title("Welcome to turtle project")
t =turtle.Turtle()
t.fillcolor("red")
t.begin_fill()
t.forward(100)
t.left(120)
t.forward(100)
t.left(120)
t.forward(100)
t.left(120)
t.forward(100)
t.left(100)
t.forward(100)
t.left(100)
t.forward(100)
t.right(100)
t.forward(100)
t.right(100)
turtle.done()